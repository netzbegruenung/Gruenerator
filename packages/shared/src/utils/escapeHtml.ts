/**
 * Escape the five reserved HTML characters for safe embedding in markup.
 * Works in any JS runtime — no DOM dependency.
 */
export function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
