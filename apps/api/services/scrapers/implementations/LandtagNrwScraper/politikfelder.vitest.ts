describe('politikfelder', () => {
  it('assigns every Sachgebiet of the search form to a Politikfeld', () => {
    expect(FORM_SYSTEMATIK).toHaveLength(159);
    expect(FORM_SYSTEMATIK.filter((s) => politikfeldOf(s) === null)).toEqual([]);
  });

  it('reads the mixed case of the result list, including ß', () => {
    expect(politikfeldOf('Straßenverkehr')).toBe('Verkehr & Mobilität');
    expect(politikfeldOf('Außenpolitik')).toBe('Europa & Internationales');
  });

  it('dedupes Politikfelder of one document', () => {
    expect(politikfelderOf(['Schulen', 'Bildung', 'Religionsgemeinschaften'])).toEqual([
      'Bildung & Schule',
      'Migration, Integration & Religion',
    ]);
  });

  it('drops an unknown Sachgebiet instead of inventing a field', () => {
    expect(politikfelderOf(['Gibt es nicht'])).toEqual([]);
  });

  it('keeps the field list short enough for a filter', () => {
    expect(POLITIKFELD_NAMES.length).toBeLessThanOrEqual(20);
  });
});
