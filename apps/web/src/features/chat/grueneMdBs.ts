const INDEX: Array<{ searchKey: string; mdb: MdB }> = GRUENE_MDBS.map((mdb) => ({
  searchKey: `${mdb.name} ${mdb.bundesland}`.toLowerCase(),
  mdb,
}));

export function searchMdBs(query: string, limit = 5): MdB[] {
  if (!query || query.length < 2) return [];
  const q = query.toLowerCase();
  const results: MdB[] = [];
  for (const entry of INDEX) {
    if (entry.searchKey.includes(q)) {
      results.push(entry.mdb);
      if (results.length >= limit) break;
    }
  }
  return results;
}
